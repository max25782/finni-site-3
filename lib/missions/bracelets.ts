export const GOAL_PROFIT = 50;
export const PARTNER_SHARE = 0.25;

const fl = Math.floor;
const rd = Math.round;
const maxUnits = (v: V) => Math.max(0, fl(v.cash / Math.max(1, v.unitCost)));

/** Как цена влияет на спрос: дёшево = берут охотно, слишком дорого = проходят мимо. */
export function priceEffect(v: V): number {
  const r = v.price / Math.max(1, v.unitCost);
  let e = r <= 1.5 ? 5 : r <= 2.5 ? 2 : r <= 4 ? 0 : -4;
  if (v.price > 20) e -= 3;
  return e;
}

export function sim1(v: V) {
  const demand = Math.max(0, 1 + v.demandBonus + v.quality + priceEffect(v));
  const sold = Math.min(v.stock, demand);
  return { demand, sold, rev: sold * v.price };
}

export function sim2(v: V) {
  const demand = Math.max(0, 4 + fl(v.demandBonus / 2) + v.rep + priceEffect(v));
  const sold = Math.min(v.stock, demand);
  return { demand, sold, rev: sold * v.price };
}

export const creditPayback = (v: V) => (v.credit === 1 ? rd(v.owed * 0.6) : 0);
export const partnerShare = (v: V) => (v.partner ? rd(v.revenue * PARTNER_SHARE) : 0);
export const finalProfit = (v: V) => v.revenue - v.costs - partnerShare(v);

function priceComment(v: V): L {
  const r = v.price / Math.max(1, v.unitCost);
  if (v.price > 20)
    return L(
      "Многие читали ценник и шли дальше: дорого для школьной ярмарки.",
      "הרבה קראו את המחיר והמשיכו הלאה: יקר ליריד בית ספר."
    );
  if (r <= 1.5)
    return L(
      "Браслеты разлетаются мгновенно, но прибыль с каждого совсем маленькая.",
      "הצמידים נחטפים מיד, אבל הרווח מכל אחד קטן מאוד."
    );
  if (r <= 2.5) return L("Цена в самый раз: честная для покупателей и выгодная тебе.", "המחיר מאוזן: הוגן לקונים ומשתלם לך.");
  return L(
    "Цена кусается: часть людей любуется браслетами, но не покупает.",
    "המחיר עוקץ: חלק מהאנשים מתפעלים מהצמידים אבל לא קונים."
  );
}

