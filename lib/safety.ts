// Грубый, но осторожный детектор личных и платёжных данных.
// Работает и в браузере (до отправки), и на сервере (повторная проверка).
// Цель: такое сообщение НЕ уходит в модель, НЕ показывается обратно и НЕ сохраняется.

const PATTERNS: RegExp[] = [
  /(?:\d[ -]?){13,19}/, // номер карты (13-19 цифр, возможно с пробелами)
  /\b(?:cvv|cvc|пин|pin|פין)\b/i,
  /(?:\+?972|\b0)[ -]?5\d[ -]?\d{3}[ -]?\d{4}\b/, // телефон Израиль
  /\+?\d[\d -]{9,14}\d/, // другие телефоны
  /\b\d{9}\b/, // теудат зеут (9 цифр)
  /[\w.+-]+@[\w-]+\.[\w.]+/, // email
  /(?:парол|password|סיסמ)\w*\s*[:=\-]?\s*\S+/i,
  /(?:код|sms|смс|קוד)\s*(?:из|from)?\s*[:=\-]?\s*\d{4,8}/i,
  /(?:мой адрес|я живу на|живу на улице|אני גר|אני גרה|הכתובת שלי)/i,
];

export function containsPrivateData(text: string): boolean {
  return PATTERNS.some((p) => p.test(text));
}

