export function questById(id: string): Quest | undefined {
  return QUESTS.find((q) => q.id === id);
}

export function questForDay(dayIdx: number, completed: string[]): Quest {
  // сначала непройденные, потом по кругу
  const fresh = QUESTS.filter((q) => !completed.includes(q.id));
  const pool = fresh.length ? fresh : QUESTS;
  return pool[dayIdx % pool.length];
}

export function text(q: Quest, lang: Lang): QuestText {
  return q[lang];
}
